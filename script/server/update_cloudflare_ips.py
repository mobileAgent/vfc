#!/usr/bin/env python3
"""Keep the origin's Cloudflare-only lockdown in step with Cloudflare's ranges.

Fetches Cloudflare's published address ranges and, when they have changed,
rewrites the three files that depend on them, checks them, and applies them:

  /etc/apache2/cloudflare-ips.txt     mod_remoteip's trusted proxy list
  /etc/apache2/cloudflare-only.conf   the per-site Require expr lockdown
  /etc/nftables-cloudflare.nft        the firewall rule: ports 80 and 443
                                      only from Cloudflare (plus loopback)

If either check fails (nft -c, apache2ctl configtest) or applying fails, the
previous files are put back and re-applied, and the script exits non-zero
so cron mails the output. SSH, mail and every other port are untouched.

The nft file replaces its own table in a single transaction, so there is no
moment where the ports are open to everyone or closed to Cloudflare. Load it
at boot by adding to /etc/nftables.conf:

  include "/etc/nftables-cloudflare.nft"

Usage (as root):
  update-cloudflare-ips --dry-run   # show what would change, touch nothing
  update-cloudflare-ips --force     # write and apply even if unchanged
  update-cloudflare-ips             # weekly from cron; quiet when unchanged

Only uses the Python 3 standard library.
"""

import argparse
import difflib
import ipaddress
import os
import subprocess
import sys
import syslog
import tempfile
import urllib.request
from datetime import datetime, timezone

SOURCES = ['https://www.cloudflare.com/ips-v4', 'https://www.cloudflare.com/ips-v6']
# Sanity limits on what Cloudflare sends back, so a broken or hijacked
# response can never open the ports to everyone or lock Cloudflare out.
MIN_V4, MIN_V6 = 8, 4
SHORTEST_V4, SHORTEST_V6 = 8, 20      # no v4 range wider than /8, no v6 wider than /20
PORTS = '80, 443'


def parse_args():
    p = argparse.ArgumentParser(description=__doc__.split('\n\n')[0])
    p.add_argument('--dry-run', action='store_true', help='show the changes, write nothing')
    p.add_argument('--force', action='store_true', help='write and apply even if nothing changed')
    p.add_argument('--no-apply', action='store_true',
                   help='write and check the files but do not load them (for testing)')
    p.add_argument('--from-file', metavar='PATH',
                   help='read the ranges from a local file instead of Cloudflare (for testing)')
    p.add_argument('--ips-file', default='/etc/apache2/cloudflare-ips.txt')
    p.add_argument('--apache-file', default='/etc/apache2/cloudflare-only.conf')
    p.add_argument('--nft-file', default='/etc/nftables-cloudflare.nft')
    return p.parse_args()


def fetch(args):
    if args.from_file:
        with open(args.from_file) as f:
            texts = [f.read()]
    else:
        texts = []
        for url in SOURCES:
            req = urllib.request.Request(url, headers={'User-Agent': 'origin-ip-updater/1.0'})
            with urllib.request.urlopen(req, timeout=30) as r:
                if r.status != 200:
                    raise ValueError('%s answered %s' % (url, r.status))
                texts.append(r.read().decode('ascii'))
    nets = []
    for text in texts:
        for word in text.split():
            nets.append(ipaddress.ip_network(word, strict=True))
    v4 = sorted({n for n in nets if n.version == 4})
    v6 = sorted({n for n in nets if n.version == 6})
    if len(v4) < MIN_V4 or len(v6) < MIN_V6:
        raise ValueError('only %d IPv4 and %d IPv6 ranges; expected at least %d and %d'
                         % (len(v4), len(v6), MIN_V4, MIN_V6))
    for n in v4 + v6:
        if n.prefixlen < (SHORTEST_V4 if n.version == 4 else SHORTEST_V6):
            raise ValueError('range %s is implausibly wide' % n)
        if n.is_private or n.is_loopback or n.is_multicast or n.is_unspecified:
            raise ValueError('range %s is not a public address range' % n)
    return v4, v6


def render(v4, v6):
    stamp = datetime.now(timezone.utc).strftime('%Y-%m-%d %H:%M UTC')
    head = 'Generated by update-cloudflare-ips from %s; do not edit by hand.' % ', '.join(SOURCES)
    ips = ''.join('%s\n' % n for n in v4 + v6)
    apache = ('# %s\n' % head +
              'Require expr "' +
              ' || '.join("%%{CONN_REMOTE_ADDR} -ipmatch '%s'" % n for n in v4 + v6) +
              '"\n')
    nft = '''# {head}
# Ranges as of {stamp}.
#
# Ports {ports} accept new connections only from Cloudflare (and loopback).
# Everything else is dropped silently: no TLS handshake, no 403, nothing
# sent back. The first two lines make the reload replace this table in one
# transaction, whether or not it already exists.
table inet cfonly
delete table inet cfonly

table inet cfonly {{
\tset cf4 {{
\t\ttype ipv4_addr; flags interval
\t\telements = {{ {v4} }}
\t}}
\tset cf6 {{
\t\ttype ipv6_addr; flags interval
\t\telements = {{ {v6} }}
\t}}
\tchain input {{
\t\ttype filter hook input priority -5; policy accept;
\t\tiifname "lo" accept
\t\ttcp dport {{ {ports} }} ip saddr @cf4 accept
\t\ttcp dport {{ {ports} }} ip6 saddr @cf6 accept
\t\ttcp dport {{ {ports} }} counter drop comment "not from Cloudflare"
\t}}
}}
'''.format(head=head, stamp=stamp, ports=PORTS,
           v4=', '.join(map(str, v4)), v6=', '.join(map(str, v6)))
    return {'ips': ips, 'apache': apache, 'nft': nft}


def read(path):
    try:
        with open(path) as f:
            return f.read()
    except FileNotFoundError:
        return None


def ranges_in(text):
    """The set of ranges a file mentions, ignoring comments and timestamps."""
    if text is None:
        return None
    found = set()
    for word in text.replace(',', ' ').replace("'", ' ').replace('{', ' ').replace('}', ' ').split():
        try:
            found.add(ipaddress.ip_network(word, strict=False))
        except ValueError:
            pass
    return found


def write_atomic(path, text):
    d = os.path.dirname(path) or '.'
    fd, tmp = tempfile.mkstemp(dir=d, prefix='.' + os.path.basename(path) + '.')
    try:
        with os.fdopen(fd, 'w') as f:
            f.write(text)
        os.chmod(tmp, 0o644)
        os.replace(tmp, path)
    except BaseException:
        if os.path.exists(tmp):
            os.unlink(tmp)
        raise


def run(cmd):
    r = subprocess.run(cmd, stdout=subprocess.PIPE, stderr=subprocess.STDOUT, universal_newlines=True)
    if r.returncode != 0:
        raise RuntimeError('%s failed:\n%s' % (' '.join(cmd), r.stdout.strip()))


def check_and_apply(args):
    run(['nft', '-c', '-f', args.nft_file])
    run(['apache2ctl', 'configtest'])
    if not args.no_apply:
        run(['nft', '-f', args.nft_file])
        run(['systemctl', 'reload', 'apache2'])


def say(msg, error=False):
    (sys.stderr if error else sys.stdout).write(msg + '\n')
    syslog.syslog(syslog.LOG_ERR if error else syslog.LOG_NOTICE, msg)


def main():
    args = parse_args()
    syslog.openlog('update-cloudflare-ips')
    try:
        v4, v6 = fetch(args)
    except Exception as e:
        say('not updating: could not get Cloudflare ranges: %s' % e, error=True)
        return 1

    new = render(v4, v6)
    paths = {'ips': args.ips_file, 'apache': args.apache_file, 'nft': args.nft_file}
    old = {k: read(p) for k, p in paths.items()}
    wanted = set(v4 + v6)
    stale = [k for k in paths if ranges_in(old[k]) != wanted]

    if not stale and not args.force:
        return 0
    if args.dry_run:
        for k in paths:
            diff = difflib.unified_diff((old[k] or '').splitlines(True), new[k].splitlines(True),
                                        paths[k] + ' (now)', paths[k] + ' (new)')
            sys.stdout.writelines(diff)
        print('\n%d IPv4 and %d IPv6 ranges; out of date: %s' % (len(v4), len(v6), ', '.join(stale) or 'none'))
        return 0

    for k, p in paths.items():
        write_atomic(p, new[k])
    try:
        check_and_apply(args)
    except Exception as e:
        say('new Cloudflare ranges rejected, putting the old files back: %s' % e, error=True)
        for k, p in paths.items():
            if old[k] is None:
                os.unlink(p)
            else:
                write_atomic(p, old[k])
        if old['nft'] is None and not args.no_apply:
            # First run: nothing to go back to, so take the new table out again.
            subprocess.run(['nft', 'delete', 'table', 'inet', 'cfonly'],
                           stdout=subprocess.DEVNULL, stderr=subprocess.DEVNULL)
        if all(old[k] is not None for k in paths):
            try:
                check_and_apply(args)
            except Exception as e2:
                say('re-applying the old files also failed: %s' % e2, error=True)
        return 1

    say('Cloudflare ranges %s: %d IPv4, %d IPv6 (%s)'
        % ('applied' if not args.no_apply else 'written', len(v4), len(v6),
           'changed: ' + ', '.join(stale) if stale else 'forced, unchanged'))
    return 0


if __name__ == '__main__':
    sys.exit(main())
